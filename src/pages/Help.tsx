import { useMemo, useState } from "react";
import { Link } from "react-router-dom";
import {
  BookOpen,
  Download,
  FileText,
  LifeBuoy,
  MessageSquare,
  Phone,
  Search,
  Send,
  Video,
} from "lucide-react";
import { useApp } from "../context/AppContext";
import {
  Accordion,
  Badge,
  Button,
  Card,
  CardHeader,
  FieldError,
  Input,
  Label,
  PageHeader,
  Select,
  Textarea,
  cx,
} from "../components/ui";
import { FAQS, MANUALS } from "../lib/data";

const SUBJECTS = [
  "Document verification issue",
  "Land record not found",
  "Mutation / Dakhil-Kharij",
  "Encumbrance certificate",
  "Cadastral map discrepancy",
  "RTI application",
  "Login / OTP problem",
  "Other",
];

export default function Help() {
  const { t, lang, toast, addTicket, tickets, session } = useApp();
  const L = (en: string, hi: string) => (lang === "hi" ? hi : en);

  const cats = useMemo(() => ["All", ...Array.from(new Set(FAQS.map((f) => f.cat)))], []);
  const [cat, setCat] = useState("All");
  const [q, setQ] = useState("");

  const filtered = useMemo(() => {
    const needle = q.trim().toLowerCase();
    return FAQS.filter((f) => {
      if (cat !== "All" && f.cat !== cat) return false;
      if (!needle) return true;
      return (
        f.q.toLowerCase().includes(needle) ||
        f.qHi.includes(needle) ||
        f.a.toLowerCase().includes(needle)
      );
    });
  }, [cat, q]);

  const [form, setForm] = useState({
    name: session?.name ?? "",
    email: "",
    phone: "",
    subject: SUBJECTS[0],
    message: "",
  });
  const [errors, setErrors] = useState<Record<string, string>>({});

  const submitTicket = (e: React.FormEvent) => {
    e.preventDefault();
    const err: Record<string, string> = {};
    if (form.name.trim().length < 3) err.name = t("c.required");
    if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(form.email))
      err.email = L("Enter a valid email address.", "मान्य ईमेल पता दर्ज करें।");
    if (!/^[6-9]\d{9}$/.test(form.phone))
      err.phone = L("Enter a valid 10-digit mobile number.", "मान्य 10-अंकीय मोबाइल नंबर दर्ज करें।");
    if (form.message.trim().length < 20)
      err.message = L("Please describe your issue in at least 20 characters.", "कृपया अपनी समस्या कम से कम 20 अक्षरों में बताएँ।");
    setErrors(err);
    if (Object.keys(err).length) return;

    const ref = `TKT/${new Date().getFullYear()}/${String(Math.floor(Math.random() * 90000) + 10000)}`;
    addTicket({
      id: ref,
      ref,
      name: form.name,
      subject: form.subject,
      message: form.message,
      createdAt: new Date().toISOString(),
    });
    toast(`${L("Ticket registered", "टिकट पंजीकृत")}: ${ref}`);
    setForm((f) => ({ ...f, message: "", subject: SUBJECTS[0] }));
  };

  const downloadManual = (name: string) => {
    const text = [
      "BHOOMI VERIFY AI — USER DOCUMENTATION",
      "Department of Land Resources, Ministry of Rural Development, Government of India",
      "=".repeat(72),
      "",
      `Document : ${name}`,
      `Issued   : ${new Date().toLocaleDateString("en-IN")}`,
      `Version  : 3.2`,
      "",
      "1. OVERVIEW",
      "   BhoomiVerify AI provides AI-assisted authenticity verification of land",
      "   documents and consolidated access to Records of Rights across States.",
      "",
      "2. VERIFYING A DOCUMENT",
      "   a) Open 'Verify Document' from the main navigation.",
      "   b) Click 'Browse Files' or drag a PDF/JPG/PNG/WEBP file (max 10 MB).",
      "   c) Select the document type and the State it was issued in.",
      "   d) Click 'Start AI Verification' and wait for the five-stage pipeline.",
      "   e) Review the verdict, security checks and extracted OCR fields.",
      "   f) Download the report or save it to your dashboard.",
      "",
      "3. SEARCHING LAND RECORDS",
      "   Select State > District > Tehsil > Village, or search directly by",
      "   Khasra number / record-holder name, then press Search.",
      "",
      "4. FILING AN RTI APPLICATION",
      "   Use the RTI page: fill applicant details, describe the information",
      "   sought, pay the Rs.10 fee (BPL applicants exempt) and submit.",
      "",
      "5. HELPLINE",
      "   Kisan Call Centre 1800-11-1551 (toll free, 06:00-22:00, all days)",
      "   Email: support-bhumiverify@nic.in",
      "",
      "-".repeat(72),
      "This is a sample document generated by the BhoomiVerify AI prototype.",
    ].join("\n");
    const blob = new Blob([text], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${name.replace(/[^a-z0-9]+/gi, "-")}.txt`;
    a.click();
    setTimeout(() => URL.revokeObjectURL(url), 1500);
    toast(L("Manual downloaded", "मैनुअल डाउनलोड हुआ"));
  };

  return (
    <>
      <PageHeader
        title={t("h.title")}
        subtitle={t("h.sub")}
        icon={<LifeBuoy size={22} />}
        breadcrumb={[{ label: t("nav.home"), to: "/" }, { label: t("nav.help") }]}
        actions={
          <a href="tel:1800111551">
            <Button variant="secondary" size="sm">
              <Phone size={15} /> 1800-11-1551
            </Button>
          </a>
        }
      />

      <div className="mx-auto max-w-[1240px] px-4 py-8 sm:px-6">
        <div className="grid gap-6 lg:grid-cols-[minmax(0,1fr)_21rem]">
          <div className="space-y-6">
            {/* FAQ */}
            <section>
              <div className="mb-4">
                <h2 className="text-xl font-extrabold tracking-tight text-gov-900 dark:text-white">
                  {t("h.faq")}
                </h2>
                <div className="mt-1.5 h-1 w-16 rounded-full bg-gradient-to-r from-saffron-500 to-leaf-500" />
              </div>

              <Card className="mb-4 p-4">
                <div className="flex flex-wrap items-center gap-3">
                  <div className="relative min-w-[14rem] flex-1">
                    <Search
                      size={16}
                      className="pointer-events-none absolute left-3 top-1/2 -translate-y-1/2 text-slate-400"
                      aria-hidden
                    />
                    <Input
                      value={q}
                      onChange={(e) => setQ(e.target.value)}
                      className="pl-9"
                      placeholder={L("Search the knowledge base…", "ज्ञान आधार में खोजें…")}
                      aria-label="Search FAQs"
                    />
                  </div>
                  <div className="flex flex-wrap gap-1.5">
                    {cats.map((c) => (
                      <button
                        key={c}
                        type="button"
                        onClick={() => setCat(c)}
                        aria-pressed={cat === c}
                        className={cx(
                          "rounded-full border px-3 py-1.5 text-[0.75rem] font-bold transition",
                          cat === c
                            ? "border-gov-700 bg-gov-700 text-white"
                            : "border-slate-300 bg-white text-slate-600 hover:border-gov-400 hover:text-gov-700 dark:border-white/15 dark:bg-transparent dark:text-slate-300",
                        )}
                      >
                        {c === "All" ? t("c.all") : c}
                      </button>
                    ))}
                  </div>
                </div>
              </Card>

              {filtered.length ? (
                <Accordion
                  items={filtered.map((f, i) => ({
                    id: `${cat}-${i}`,
                    title: (
                      <span className="flex flex-wrap items-center gap-2">
                        <Badge tone="blue">{f.cat}</Badge>
                        {lang === "hi" ? f.qHi : f.q}
                      </span>
                    ),
                    body: lang === "hi" ? f.aHi : f.a,
                  }))}
                />
              ) : (
                <Card className="grid place-items-center px-6 py-14 text-center">
                  <p className="text-sm font-semibold text-slate-700 dark:text-slate-200">
                    {t("c.none")}
                  </p>
                  <Button
                    variant="secondary"
                    className="mt-4"
                    onClick={() => {
                      setQ("");
                      setCat("All");
                    }}
                  >
                    {t("lr.clear")}
                  </Button>
                </Card>
              )}
            </section>

            {/* ticket */}
            <Card id="ticket">
              <CardHeader title={t("h.ticket")} icon={<MessageSquare size={15} />} />
              <p className="border-b border-slate-200 px-5 py-3 text-[0.8rem] text-slate-600 dark:border-white/10 dark:text-slate-300">
                {t("h.ticketSub")}
              </p>
              <form className="grid gap-4 p-5 sm:grid-cols-2" onSubmit={submitTicket}>
                <div>
                  <Label htmlFor="tk-name" required>
                    {t("c.name")}
                  </Label>
                  <Input
                    id="tk-name"
                    value={form.name}
                    onChange={(e) => setForm({ ...form, name: e.target.value })}
                    invalid={!!errors.name}
                  />
                  <FieldError>{errors.name}</FieldError>
                </div>
                <div>
                  <Label htmlFor="tk-email" required>
                    {t("c.email")}
                  </Label>
                  <Input
                    id="tk-email"
                    type="email"
                    value={form.email}
                    onChange={(e) => setForm({ ...form, email: e.target.value })}
                    invalid={!!errors.email}
                  />
                  <FieldError>{errors.email}</FieldError>
                </div>
                <div>
                  <Label htmlFor="tk-phone" required>
                    {t("c.phone")}
                  </Label>
                  <Input
                    id="tk-phone"
                    inputMode="numeric"
                    maxLength={10}
                    value={form.phone}
                    onChange={(e) =>
                      setForm({ ...form, phone: e.target.value.replace(/\D/g, "").slice(0, 10) })
                    }
                    invalid={!!errors.phone}
                  />
                  <FieldError>{errors.phone}</FieldError>
                </div>
                <div>
                  <Label htmlFor="tk-subject" required>
                    {t("ct.subject")}
                  </Label>
                  <Select
                    id="tk-subject"
                    value={form.subject}
                    onChange={(e) => setForm({ ...form, subject: e.target.value })}
                  >
                    {SUBJECTS.map((s) => (
                      <option key={s} value={s}>
                        {s}
                      </option>
                    ))}
                  </Select>
                </div>
                <div className="sm:col-span-2">
                  <Label htmlFor="tk-msg" required>
                    {L("Describe your issue", "अपनी समस्या का विवरण दें")}
                  </Label>
                  <Textarea
                    id="tk-msg"
                    value={form.message}
                    onChange={(e) => setForm({ ...form, message: e.target.value })}
                    invalid={!!errors.message}
                    placeholder={L(
                      "Include record IDs, reference numbers and the steps you already tried…",
                      "अभिलेख आईडी, संदर्भ संख्या और आपके द्वारा किए गए चरण अवश्य लिखें…",
                    )}
                  />
                  <FieldError>{errors.message}</FieldError>
                </div>
                <div className="sm:col-span-2">
                  <Button type="submit" size="lg">
                    <Send size={17} /> {L("Submit Ticket", "टिकट जमा करें")}
                  </Button>
                </div>
              </form>

              {tickets.length ? (
                <div className="border-t border-slate-200 dark:border-white/10">
                  <p className="px-5 pt-4 text-[0.78rem] font-bold uppercase tracking-wide text-slate-500 dark:text-slate-400">
                    {L("Your tickets", "आपके टिकट")}
                  </p>
                  <ul className="divide-y divide-slate-100 p-0 dark:divide-white/5">
                    {tickets.slice(0, 4).map((tk) => (
                      <li key={tk.id} className="flex flex-wrap items-center gap-3 px-5 py-3">
                        <span className="tabular rounded bg-gov-50 px-2 py-0.5 text-[0.7rem] font-bold text-gov-700 dark:bg-gov-800 dark:text-gov-200">
                          {tk.ref}
                        </span>
                        <span className="min-w-0 flex-1 truncate text-[0.82rem] font-medium text-slate-700 dark:text-slate-200">
                          {tk.subject}
                        </span>
                        <Badge tone="amber">{L("Open", "खुला")}</Badge>
                      </li>
                    ))}
                  </ul>
                </div>
              ) : null}
            </Card>
          </div>

          {/* sidebar */}
          <aside className="space-y-5">
            <Card>
              <CardHeader title={t("h.docs")} icon={<BookOpen size={15} />} />
              <ul className="divide-y divide-slate-100 dark:divide-white/5">
                {MANUALS.map((m) => (
                  <li key={m.name} className="flex items-center gap-3 px-5 py-3.5">
                    <span className="grid h-9 w-9 shrink-0 place-items-center rounded bg-red-50 text-red-600 dark:bg-red-500/15 dark:text-red-400">
                      <FileText size={17} />
                    </span>
                    <div className="min-w-0 flex-1">
                      <p className="truncate text-[0.82rem] font-bold text-slate-800 dark:text-slate-100">
                        {lang === "hi" ? m.nameHi : m.name}
                      </p>
                      <p className="tabular mt-0.5 text-[0.7rem] text-slate-500 dark:text-slate-400">
                        PDF · {m.size} · {m.pages} {L("pages", "पृष्ठ")}
                      </p>
                    </div>
                    <Button size="sm" variant="ghost" onClick={() => downloadManual(m.name)} aria-label={`Download ${m.name}`}>
                      <Download size={15} />
                    </Button>
                  </li>
                ))}
              </ul>
            </Card>

            <Card>
              <CardHeader title={L("Video Tutorials", "वीडियो ट्यूटोरियल")} icon={<Video size={15} />} />
              <ul className="divide-y divide-slate-100 dark:divide-white/5">
                {[
                  [L("How to upload & verify a document", "दस्तावेज़ अपलोड एवं सत्यापन कैसे करें"), "4:12"],
                  [L("Searching RoR by Khasra number", "खसरा संख्या से RoR खोजना"), "3:05"],
                  [L("Filing an RTI application online", "ऑनलाइन आरटीआई आवेदन दर्ज करना"), "6:48"],
                  [L("Reading a cadastral map sheet", "भू-नक़्शा शीट पढ़ना"), "5:20"],
                ].map(([title, dur]) => (
                  <li key={title}>
                    <button
                      type="button"
                      onClick={() =>
                        toast(L("Video tutorials will open in the NIC media player.", "वीडियो ट्यूटोरियल एनआईसी मीडिया प्लेयर में खुलेंगे।"), "info")
                      }
                      className="group flex w-full items-center gap-3 px-5 py-3 text-left transition hover:bg-gov-50/70 dark:hover:bg-white/5"
                    >
                      <span className="grid h-9 w-9 shrink-0 place-items-center rounded-full bg-gov-700 text-white transition group-hover:bg-leaf-600">
                        <svg width="11" height="12" viewBox="0 0 11 12" aria-hidden>
                          <path d="M0 0l11 6-11 6z" fill="currentColor" />
                        </svg>
                      </span>
                      <span className="min-w-0 flex-1 text-[0.8rem] font-semibold text-slate-700 dark:text-slate-200">
                        {title}
                      </span>
                      <span className="tabular shrink-0 text-[0.7rem] font-bold text-slate-400">
                        {dur}
                      </span>
                    </button>
                  </li>
                ))}
              </ul>
            </Card>

            <Card className="border-gov-300 bg-gradient-to-br from-gov-50 to-white dark:border-gov-700 dark:from-gov-900/60 dark:to-gov-950">
              <div className="p-5">
                <h3 className="text-[0.95rem] font-bold text-gov-900 dark:text-white">
                  {L("Still need assistance?", "अभी भी सहायता चाहिए?")}
                </h3>
                <p className="mt-1.5 text-[0.8rem] leading-relaxed text-slate-600 dark:text-slate-300">
                  {L(
                    "Write to the helpdesk or call the toll-free Kisan Call Centre. Officers may raise a ticket through the internal service desk.",
                    "हेल्पडेस्क को लिखें या टोल-फ्री किसान कॉल सेंटर पर कॉल करें। अधिकारी आंतरिक सर्विस डेस्क के माध्यम से टिकट दर्ज कर सकते हैं।",
                  )}
                </p>
                <Link to="/contact" className="mt-3.5 block">
                  <Button className="w-full">
                    <MessageSquare size={16} /> {t("nav.contact")}
                  </Button>
                </Link>
              </div>
            </Card>
          </aside>
        </div>
      </div>
    </>
  );
}
